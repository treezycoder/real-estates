import { randomBytes } from "node:crypto";
import { copyFileSync, existsSync, writeFileSync } from "node:fs";
import path from "node:path";
import { stdin, stdout } from "node:process";
import { createInterface } from "node:readline/promises";

const root = process.cwd();
const rl = createInterface({ input: stdin, output: stdout });

type Check = (v: string) => string | null;

async function ask(question: string, fallback = "", check?: Check) {
  for (;;) {
    const raw = (
      await rl.question(
        fallback ? `${question} [${fallback}]: ` : `${question}: `,
      )
    ).trim();
    const value = raw || fallback;
    const problem = check?.(value);
    if (!problem) return value;
    console.log(`  ✗ ${problem}`);
  }
}

const required: Check = (v) => (v ? null : "This field is required");
const emailRe = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
const emailList: Check = (v) =>
  v.split(",").every((e) => emailRe.test(e.trim()))
    ? null
    : "Enter valid email address(es)";
const hexColor: Check = (v) =>
  /^#[0-9a-f]{6}$/i.test(v) ? null : "Use a 6-digit hex color, e.g. #0f766e";
const isoCode: Check = (v) =>
  /^[A-Za-z]{3}$/.test(v) ? null : "Use a 3-letter ISO code, e.g. XAF";
const isoOrNone: Check = (v) =>
  v.toLowerCase() === "none" ||
  v.split(",").every((c) => /^[A-Za-z]{3}$/.test(c.trim()))
    ? null
    : "Use ISO codes like EUR,USD (or 'none')";
const langCheck: Check = (v) =>
  v === "en" || v === "fr" ? null : "Choose en or fr";
const httpsUrl: Check = (v) => {
  try {
    return new URL(v).protocol === "https:" ? null : "Use an https:// URL";
  } catch {
    return "Enter a full URL, e.g. https://example.com";
  }
};
const latLng: Check = (v) => {
  const [lat, lng] = v.split(",").map(Number);
  return Number.isFinite(lat) &&
    Number.isFinite(lng) &&
    Math.abs(lat) <= 90 &&
    Math.abs(lng) <= 180
    ? null
    : "Use the form 5.95,12.35";
};

// white or dark text, whichever is readable on the primary color
function readableOn(hex: string) {
  const n = parseInt(hex.slice(1), 16);
  const luminance =
    (0.299 * ((n >> 16) & 255) + 0.587 * ((n >> 8) & 255) + 0.114 * (n & 255)) /
    255;
  return luminance > 0.6 ? "#0f172a" : "#ffffff";
}

async function main() {
  console.log("\nNew client setup. Press Enter to accept the [default].\n");

  const name = await ask("Business name", "", required);
  const email = await ask("Contact email", "", (v) =>
    emailRe.test(v) ? null : "Enter a valid email",
  );
  const phone = await ask("Phone (as displayed on the site)", "+237 ");
  const whatsappDigits = (
    await ask("WhatsApp number (international format)", phone)
  ).replace(/\D/g, "");
  const address = await ask("Address (city, country)", "Douala, Cameroon");
  const primary = await ask("Primary brand color", "#0f766e", hexColor);
  const accent = await ask("Accent color", "#f59e0b", hexColor);
  const [lat, lng] = (
    await ask("Default map center (lat,lng)", "5.95,12.35", latLng)
  )
    .split(",")
    .map(Number);
  const currency = (
    await ask("Default currency (ISO code)", "XAF", isoCode)
  ).toUpperCase();
  const extra = await ask(
    "Other currencies to offer, comma separated (or 'none')",
    "EUR,USD",
    isoOrNone,
  );
  const adminLocale = await ask(
    "Language for admin notification emails (en/fr)",
    "en",
    langCheck,
  );
  const siteUrl = (
    await ask("Production URL", "https://example.com", httpsUrl)
  ).replace(/\/$/, "");
  const adminEmails = await ask(
    "Admin Google email(s), comma separated",
    email,
    emailList,
  );

  rl.close();

  const supported = [
    ...new Set([
      currency,
      ...(extra.toLowerCase() === "none"
        ? []
        : extra.split(",").map((c) => c.trim().toUpperCase())),
    ]),
  ];

  const config = {
    name,
    logo: "/logo.svg",
    contact: { email, phone, whatsapp: `+${whatsappDigits}`, address },
    socials: { facebook: "", instagram: "", linkedin: "" },
    currency: { default: currency, supported },
    theme: {
      primary,
      primaryForeground: readableOn(primary),
      accent,
      radius: "0.75rem",
    },
    map: { center: [lat, lng], zoom: 6 },
    adminLocale,
  };

  const clientPath = path.join(root, "src/config/client.ts");
  if (existsSync(clientPath)) copyFileSync(clientPath, `${clientPath}.bak`);
  writeFileSync(
    clientPath,
    `import type { ClientConfig } from "./types";\n\n// Generated by \`npm run init:client\`. Safe to edit by hand.\nexport const client: ClientConfig = ${JSON.stringify(config, null, 2)};\n`,
  );
  console.log(
    "\n✓ Wrote src/config/client.ts (previous version saved as client.ts.bak)",
  );

  const envPath = path.join(root, ".env.local");
  if (existsSync(envPath)) {
    console.log("• .env.local already exists, so it was left alone.");
    console.log(`  Make sure ADMIN_EMAILS=${adminEmails} is set in it.`);
  } else {
    writeFileSync(
      envPath,
      [
        "DATABASE_URL=",
        "TENANT_ID=default",
        `BETTER_AUTH_SECRET=${randomBytes(32).toString("base64")}`,
        "BETTER_AUTH_URL=http://localhost:3000",
        "NEXT_PUBLIC_SITE_URL=http://localhost:3000",
        "GOOGLE_CLIENT_ID=",
        "GOOGLE_CLIENT_SECRET=",
        `ADMIN_EMAILS=${adminEmails}`,
        "UPLOADTHING_TOKEN=",
        "RESEND_API_KEY=",
        "EMAIL_FROM=",
        "NOTIFY_EMAILS=",
        `RATE_LIMIT_SALT=${randomBytes(16).toString("hex")}`,
        "",
      ].join("\n"),
    );
    console.log("✓ Created .env.local with generated secrets");
  }

  console.log(`
Next steps
  1. Replace public/logo.svg and src/app/favicon.ico with the client's assets
  2. Fill DATABASE_URL, GOOGLE_CLIENT_ID/SECRET and UPLOADTHING_TOKEN in .env.local
  3. npm run db:setup      (migrations + currency rates)
  4. npm run doctor        (checks everything)
  5. npm run dev

On the production host, set:
  NEXT_PUBLIC_SITE_URL=${siteUrl}
  BETTER_AUTH_URL=${siteUrl}
  Google OAuth redirect URI: ${siteUrl}/api/auth/callback/google
`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
